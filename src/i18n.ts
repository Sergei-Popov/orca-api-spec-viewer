export function stringsFor(locale: string | undefined): Strings {
  return (locale ?? '').toLowerCase().startsWith('ru') ? ru : en
}

export function format(template: string, values: Record<string, unknown>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole))
}

export function problemMessage(t: Strings, problem: Problem): string {
  const params = { ...problem.params, text: problem.text ?? '' } as Record<string, unknown>
  if (problem.rule === 'bad-key') {
    const kind = String(params.kind ?? '')
    return format(t.badKeys[kind] ?? t.badKeys.component, params)
  }
  if (problem.rule === 'invalid-enum' && params.type === 'unique') return format(t.duplicateEnum, params)
  if (problem.rule === 'wrong-type') params.expected = t.expectedPhrases[String(params.expected)] ?? params.expected
  return format(t.messagesByRule[problem.rule] ?? problem.rule, params).trim()
}
